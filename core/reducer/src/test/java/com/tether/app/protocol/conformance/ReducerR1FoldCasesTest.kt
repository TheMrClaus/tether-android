package com.tether.app.protocol.conformance

import com.tether.app.protocol.fold.initialSessionState
import com.tether.app.protocol.fold.reduce
import com.tether.app.protocol.tree.JsArr
import com.tether.app.protocol.tree.JsCodec
import com.tether.app.protocol.tree.JsObj
import com.tether.app.protocol.tree.str
import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.fail
import org.junit.Test
import org.junit.runner.RunWith
import org.junit.runners.Parameterized

/**
 * ta-d3tj.10 (R1): the reduceEvent hunks of web 19c56e25 the vendored corpus does not exercise (task reopen / terminal dedupe,
 * withdrawnQueueIds, queued held and peer sender, the spawned-run summary, the pi-dialog notice replace, the session-error
 * cap / idempotency / unstamped paths, `from`). The expected projections are the WEB's own `reduce` output, generated by
 * tools/parity/gen-r1-fold-cases.mjs from the tether tree at 19c56e25 (never hand-written), in the corpus case format.
 */
@RunWith(Parameterized::class)
class ReducerR1FoldCasesTest(private val caseName: String) {

    companion object {
        private val dir get() = File(CanonicalJson.repoRoot, "core/reducer/src/test/resources/r1-fold")

        @JvmStatic
        @Parameterized.Parameters(name = "{0}")
        fun cases(): List<Array<Any>> = dir.listFiles { f -> f.name.endsWith(".json") }!!.map { arrayOf<Any>(it.name.removeSuffix(".json")) }.sortedBy { it[0] as String }
    }

    @Test
    fun foldsLikeTheWebReduce() {
        val root = CanonicalJson.read(File(dir, "$caseName.json")) as JsObj
        var state = initialSessionState(root["initial"] as JsObj)
        val initialDiff = TreeDiff.diff(root["expectedInitialProjection"], state)
        if (initialDiff.isNotEmpty()) fail("$caseName initial: " + initialDiff.take(5).joinToString("\n") { it.render() })
        val events = (root["inputEvents"] as JsArr).map { it as JsObj }
        val steps = root["expectedProjectionAfterEachStep"] as JsArr
        assertEquals(events.size, steps.size)
        for ((index, event) in events.withIndex()) {
            state = reduce(state, event)
            val diff = TreeDiff.diff(steps[index], state, limit = 20)
            if (diff.isNotEmpty()) {
                fail("$caseName step $index (${event["type"].str}): event ${JsCodec.canonical(event).take(300)}\n" + diff.take(8).joinToString("\n") { it.render() })
            }
        }
    }

    @Test
    fun theSetOfCasesIsTheGeneratedOne() {
        assertEquals(
            listOf(
                "r1-pi-dialog-notice-replace", "r1-queue-held-peer-withdrawn", "r1-session-errors", "r1-session-errors-cap",
                "r1-spawned-run-summary", "r1-task-reopen-and-dedupe", "r1-user-message-from",
            ),
            cases().map { it[0] as String },
        )
    }
}
